func underlyingTypeOf(t types.Type) types.Type {
	var underlying types.Type
	for {
		underlying = t.Underlying()
		if underlying == t {
			return underlying
		}
	}
}

func isScalar(t types.BasicKind) bool {

	if t != types.UnsafePointer &&
		t != types.UntypedNil &&
		t != types.Rune &&
		t != types.Byte {
		return true
	}

	return false
}

