type way string

func group[E any, K comparable, V any](slice []E, f func(E) (k K, vv []V)) map[K][]V {

	var m = make(map[K][]V)

	for _, v := range slice {
		if k, vv := f(v); vv != nil {
			m[k] = append(m[k], vv...)
		}
	}

	return m
}

